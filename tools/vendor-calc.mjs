const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

export function buildModule(dataSrc, calcSrc) {
  const header = `/*! ${PIN.name} ${PIN.version} (${PIN.license}). Vendored unmodified: dist/data/production.min.js then dist/production.min.js.
${MIT(PIN.copyright).replace(/\*\//g, '* /').trimEnd().split('\n').map((l) => (l ? ` * ${l}` : ' *')).join('\n')}
 *
 * Generated by tools/vendor-calc.mjs. Do not edit; provenance in smogon-calc.SOURCE.json.
 */`;
  return `${header}
const window = {};
${dataSrc.trimEnd()}
${calcSrc.trimEnd()}
export const { ${EXPORTS.join(', ')} } = window.calc;
`;
}

