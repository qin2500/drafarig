// Dev-only (never shipped: tools/ is not embedded by scripts/build.mjs). Regenerates the vendored damage engine from a
// local, already-installed copy of the npm package @smogon/calc@0.12.0. No network access.
//
//   node tools/vendor-calc.mjs --from <path to node_modules/@smogon/calc>
//
// The two prebuilt browser bundles are pinned by sha256 and copied byte for byte. The only additions are a licence header,
// a module-scoped `const window = {}` (the bundles assign `window.calc`; the binding keeps them off the global object) and
// one named-export line. Writes:
//   public/vendor/smogon-calc-0.12.0.mjs     the ES module the browser lazy-loads and the tests import
//   public/vendor/smogon-calc.SOURCE.json    version, pins and the output hash (test/calc-engine.test.mjs checks them)
//   public/vendor/THIRD_PARTY_NOTICES.txt    licence texts for the vendored engine and the projected Showdown data
