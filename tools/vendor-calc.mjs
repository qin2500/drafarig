async function main() {
  const i = process.argv.indexOf('--from');
  if (i < 0 || !process.argv[i + 1]) throw new Error('usage: node tools/vendor-calc.mjs --from <path to node_modules/@smogon/calc>');
  const from = process.argv[i + 1];
  const files = {};
  for (const [rel, want] of Object.entries(PIN.inputs)) {
    const bytes = await readFile(join(from, rel));
    const got = sha256(bytes);
    if (got !== want) throw new Error(`vendor-calc: ${rel} sha256 ${got} does not match the pin ${want}`);
    files[rel] = bytes.toString('utf8');
  }
  const pkg = JSON.parse(files['package.json']);
  if (pkg.name !== PIN.name || pkg.version !== PIN.version || pkg.license !== PIN.license) throw new Error('vendor-calc: package.json is not the pinned release');
  const mod = buildModule(files['dist/data/production.min.js'], files['dist/production.min.js']);
  await mkdir(join(ROOT, 'public/vendor'), { recursive: true });
  await writeFile(join(ROOT, OUT), mod);
  const source = {
    name: PIN.name, version: PIN.version, license: PIN.license, copyright: PIN.copyright, repository: PIN.repository,
    npmIntegrity: PIN.integrity, inputs: PIN.inputs, output: { path: OUT, sha256: sha256(Buffer.from(mod, 'utf8')), bytes: Buffer.byteLength(mod) },
    exports: EXPORTS, generator: 'tools/vendor-calc.mjs',
  };
  await writeFile(join(ROOT, 'public/vendor/smogon-calc.SOURCE.json'), JSON.stringify(source, null, 2) + '\n');
  await writeFile(join(ROOT, 'public/vendor/THIRD_PARTY_NOTICES.txt'), notices());
  console.log(`Wrote ${OUT} (${source.output.bytes} bytes, sha256 ${source.output.sha256})`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
