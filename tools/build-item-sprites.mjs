// Dev-only (tools/ is never shipped). Builds lib/item-sprites.mjs: {itemId: spritenum} for every item in
// data/mechanics.json that Showdown draws, so the app can show item icons from Showdown's sprite sheet
// (https://play.pokemonshowdown.com/sprites/itemicons-sheet.png, 24×24 icons, 16 per row). A module in lib/ (not a data/
// file) because lib/ is already served and shipped: no new asset route and no extra fetch at runtime.
// Source: spritenum in https://play.pokemonshowdown.com/data/items.js (fetched once here). Items without one get no icon.
//
//   node tools/build-item-sprites.mjs [--from <saved items.js>]
import { readFile, writeFile } from 'node:fs/promises';
import { runInNewContext } from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SOURCE = 'https://play.pokemonshowdown.com/data/items.js';
const from = process.argv.includes('--from') ? process.argv[process.argv.indexOf('--from') + 1] : null;
const text = from ? await readFile(from, 'utf8') : await (await fetch(SOURCE)).text();
// items.js is one data assignment (exports.BattleItems = {...}); evaluated in an empty context with a time limit
const sandbox = { exports: {} };
runInNewContext(text, sandbox, { timeout: 2000 });
const items = sandbox.exports.BattleItems ?? {};
const mech = JSON.parse(await readFile(`${ROOT}data/mechanics.json`, 'utf8'));
const sprites = {};
for (const id of Object.keys(mech.items).sort()) if (Number.isInteger(items[id]?.spritenum)) sprites[id] = items[id].spritenum;
const body = Object.entries(sprites).map(([k, v]) => `${k}:${v}`).join(',');
await writeFile(`${ROOT}lib/item-sprites.mjs`, `// Generated by tools/build-item-sprites.mjs on ${new Date().toISOString().slice(0, 10)} from ${SOURCE} (spritenum). Do not edit.
// Item icons: Showdown's sheet, 24×24 icons, 16 per row; icon n sits at x = (n % 16) × 24, y = floor(n / 16) × 24.
export const ITEM_SHEET = 'https://play.pokemonshowdown.com/sprites/itemicons-sheet.png';
export const ITEM_SPRITES = Object.freeze({${body}});
/** Background offset of item icon n on the sheet, in px: [x, y]. */
export const iconOffset = (n) => [(n % 16) * 24, Math.floor(n / 16) * 24];
`);
console.log(`${Object.keys(sprites).length} of ${Object.keys(mech.items).length} items have an icon; without: ${Object.keys(mech.items).filter((i) => !(i in sprites)).join(', ') || 'none'}`);
