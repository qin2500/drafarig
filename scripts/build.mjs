// Builds the Sites Worker artifact. Zero dependencies, deterministic (no timestamps), run by `npm run build`:
//   dist/server/index.js       worker/app.mjs + the lib/ modules it imports, inlined into one self-contained ES module,
//                              with public/, lib/, data/dex.json and data/cores.json embedded (Sites Worker builds ship
//                              no asset files). ASSET_FILES is an explicit allowlist: nothing else under data/ is shipped.
//   dist/.openai/hosting.json  copied unchanged from .openai/hosting.json
// The inliner only accepts the plain module syntax this repo uses and fails loudly on anything else.
import { readFile, writeFile, mkdir, rm, readdir, copyFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const ENTRY = join(ROOT, 'worker', 'app.mjs');
const ASSET_DIRS = ['public', 'lib'];
const ASSET_FILES = ['data/dex.json', 'data/cores.json'];
const DIST = join(ROOT, 'dist');

const rel = (file) => relative(ROOT, file).split('\\').join('/');
const varName = (file) => '__' + rel(file).replace(/\.mjs$/, '').replace(/[^A-Za-z0-9_$]/g, '_');
const IMPORT = /^import \{([^}]*)\} from '(\.\.?\/[^']+\.mjs)';$/;
const EXPORT = /^export (?:async function|function|const|class) ([A-Za-z_$][\w$]*)/;

// Wraps one module in a function scope: named imports become destructured consts, exports become its return value.
async function inline(file, modules = new Map(), visiting = new Set()) {
  if (modules.has(file)) return modules;
  if (visiting.has(file)) throw new Error(`build: circular import through ${rel(file)}`);
  visiting.add(file);
  const names = [];
  const lines = [];
  for (const line of (await readFile(file, 'utf8')).split('\n')) {
    const imp = line.match(IMPORT);
    if (imp) {
      const dep = join(dirname(file), imp[2]);
      await inline(dep, modules, visiting);
      lines.push(`const {${imp[1].replace(/\bas\b/g, ':')}} = ${varName(dep)};`);
      continue;
    }
    const exp = line.match(EXPORT);
    if (exp) { names.push(exp[1]); lines.push(line.slice('export '.length)); continue; }
    if (/^\s*(import|export)\b|\bimport\s*\(|\bimport\.meta\b|\brequire\s*\(/.test(line)) {
      throw new Error(`build: unsupported module syntax in ${rel(file)}: ${line.trim()}`);
    }
    lines.push(line);
  }
  visiting.delete(file);
  modules.set(file, `// ---- ${rel(file)} ----\nconst ${varName(file)} = (() => {\n${lines.join('\n')}\nreturn { ${names.join(', ')} };\n})();\n`);
  return modules;
}

async function listFiles(dir) {
  const out = [];
  for (const entry of await readdir(join(ROOT, dir), { withFileTypes: true })) {
    const path = `${dir}/${entry.name}`;
    if (entry.isDirectory()) out.push(...await listFiles(path));
    else if (entry.isFile()) out.push(path);
    else throw new Error(`build: not a regular file: ${path}`);
  }
  return out;
}

// Embedded as JS strings; the round-trip check guarantees the Worker serves exactly the source bytes.
async function embedAssets() {
  const paths = [...(await Promise.all(ASSET_DIRS.map(listFiles))).flat(), ...ASSET_FILES].sort();
  const entries = [];
  for (const path of paths) {
    const bytes = await readFile(join(ROOT, path));
    const text = bytes.toString('utf8');
    if (!Buffer.from(text, 'utf8').equals(bytes)) throw new Error(`build: ${path} is not UTF-8 text; embed it another way`);
    entries.push(`  ${JSON.stringify(path)}: ${JSON.stringify(text).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029')},`);
  }
  return `const FILES = {\n${entries.join('\n')}\n};\n`;
}

const modules = await inline(ENTRY);
const bundle = [
  '// Generated by scripts/build.mjs from worker/app.mjs, lib/, public/, data/dex.json and data/cores.json. Do not edit.',
  ...modules.values(),
  await embedAssets(),
  `export default ${varName(ENTRY)}.createApp(FILES);`,
  '',
].join('\n');

await rm(DIST, { recursive: true, force: true });
await mkdir(join(DIST, 'server'), { recursive: true });
await mkdir(join(DIST, '.openai'), { recursive: true });
await writeFile(join(DIST, 'server', 'index.js'), bundle);
await copyFile(join(ROOT, '.openai', 'hosting.json'), join(DIST, '.openai', 'hosting.json'));
console.log(`Built ${rel(DIST)}/server/index.js (${(bundle.length / 1024).toFixed(0)} KB, ${modules.size} modules inlined)`);
